#!/usr/bin/env node
// scripts/gen-cell-widths.mjs
//
// Writes src/window-terminal/render/cell-width-table.ts: every codepoint
// whose width tmux counts as other than one cell.
//
// tmux's width of a codepoint (utf8.c, utf8_width) is its built-in override
// table (`utf8_default_width_cache`) if the codepoint is there, else
// utf8proc's: `utf8proc_charwidth`, except a private-use codepoint is one
// cell (compat/utf8proc.c). This script asks the same two sources: it
// compiles a C program against the utf8proc tmux links, and reads the
// override table out of tmux's utf8.c at the tag given.
//
// Usage: node scripts/gen-cell-widths.mjs [tmux tag, default 3.8]
// Needs a C compiler and utf8proc (`brew install utf8proc`), found through
// pkg-config.

import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const tag = process.argv[2] ?? "3.8";
const out = new URL(
  "../src/window-terminal/render/cell-width-table.ts",
  import.meta.url,
);

const C = `
#include <stdio.h>
#include <utf8proc.h>
int main(void) {
  printf("%s\\n", utf8proc_unicode_version());
  for (int c = 0; c <= 0x10FFFF; c++) {
    int w = utf8proc_category(c) == UTF8PROC_CATEGORY_CO ? 1 : utf8proc_charwidth(c);
    putchar('0' + w);
  }
  return 0;
}
`;

const dir = mkdtempSync(join(tmpdir(), "cell-widths-"));
writeFileSync(join(dir, "widths.c"), C);
const flags = execFileSync(
  "pkg-config",
  ["--cflags", "--libs", "libutf8proc"],
  {
    encoding: "utf8",
  },
)
  .trim()
  .split(/\s+/);
execFileSync("cc", [
  "-o",
  join(dir, "widths"),
  join(dir, "widths.c"),
  ...flags,
]);
const [unicode, digits] = execFileSync(join(dir, "widths"), {
  encoding: "utf8",
  maxBuffer: 0x200000,
}).split("\n");
const widths = [...digits].map(Number);

async function tmuxSource(file) {
  const url = `https://raw.githubusercontent.com/tmux/tmux/${tag}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return { url, text: await res.text() };
}

const { url, text: source } = await tmuxSource("utf8.c");
const table = /utf8_default_width_cache\[\] = \{([\s\S]*?)\n\};/.exec(source);
if (table === null) throw new Error(`${url}: no utf8_default_width_cache`);
const overrides = [
  ...table[1].matchAll(/\.wc = 0x([0-9A-Fa-f]+), \.width = (\d)/g),
];
if (overrides.length === 0) throw new Error(`${url}: empty override table`);
for (const [, wc, width] of overrides) widths[parseInt(wc, 16)] = Number(width);

// utf8-combined.c, utf8_should_combine: the emoji modifier bases a skin
// tone joins.
const combined = await tmuxSource("utf8-combined.c");
const shouldCombine = /\nutf8_should_combine\([\s\S]*?\n\}/.exec(combined.text);
if (shouldCombine === null) {
  throw new Error(`${combined.url}: no utf8_should_combine`);
}
const bases = [...shouldCombine[0].matchAll(/case 0x([0-9A-Fa-f]+):/g)].map(
  ([, wc]) => parseInt(wc, 16),
);
if (bases.length === 0) throw new Error(`${combined.url}: no modifier bases`);

// Runs of one width, as [first, last] pairs flattened.
function runs(width) {
  const flat = [];
  for (let c = 0; c < widths.length; c++) {
    if (widths[c] !== width) continue;
    const first = c;
    while (widths[c + 1] === width) c++;
    flat.push(first, c);
  }
  return flat;
}

function hexList(flat) {
  const lines = [];
  for (let i = 0; i < flat.length; i += 8) {
    const row = flat
      .slice(i, i + 8)
      .map((c) => "0x" + c.toString(16).toUpperCase());
    lines.push("  " + row.join(", ") + ",");
  }
  return lines.join("\n");
}

writeFileSync(
  out,
  `// src/window-terminal/render/cell-width-table.ts
//
// GENERATED by scripts/gen-cell-widths.mjs — do not edit. Every codepoint
// tmux ${tag} counts as zero or two cells, as [first, last] runs, ascending;
// every other codepoint is one cell. Source: utf8proc (Unicode ${unicode})
// and tmux ${tag}'s utf8_default_width_cache (${overrides.length} codepoints).
// MODIFIER_BASES: the emoji a skin tone joins, from tmux ${tag}'s
// utf8_should_combine.

export const ZERO_WIDTH: readonly number[] = [
${hexList(runs(0))}
];

export const DOUBLE_WIDTH: readonly number[] = [
${hexList(runs(2))}
];

export const MODIFIER_BASES: readonly number[] = [
${hexList(bases)}
];
`,
);
console.log(
  `wrote ${out.pathname}: Unicode ${unicode}, ${overrides.length} overrides`,
);
